"""Write and check the generated part of TESTING.md files. Standard library only.

Usage:
  py -3 -I testing_md.py update <test dir> --data <json file> [--create]
  py -3 -I testing_md.py check --workspace <ws> [--user-file <path>] [--dirs <dir> ...]

update  Rewrites everything between <!-- generated:start --> and <!-- generated:end --> in
        <test dir>/TESTING.md from the data file. The base part (everything else) is never
        touched. When TESTING.md is missing it stops, unless --create is given (only after the
        user approved the new file): then the file is made from dev-core's TESTING.md template
        with {directory} filled, and the base placeholders are left for the agent to fill.
        Data keys (strings, or lists of strings): run (ISO date and time; refused otherwise), commit, environment,
        data, results, coverage, flaky, gaps, untested. A missing key prints "none". Text that
        looks like a secret is replaced with [redacted].
check   Lists test folders (folders matching testing.test_globs that hold files) without a
        TESTING.md, and TESTING.md files whose generated part is stale: its Run time is older
        than the folder's last commit, or the folder has uncommitted changes. Without git, file
        times are compared.

Prints one JSON object with "ok".
"""

import argparse
import datetime
import fnmatch
import importlib.util
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CORE = os.path.join(HERE, "..", "..", "dev-core")
TEMPLATE = os.path.join(CORE, "assets", "templates", "TESTING.md")
START, END = "<!-- generated:start -->", "<!-- generated:end -->"
SECRET = re.compile(r"((password|pwd|secret|token|apikey|api_key|accountkey|sharedaccesskey)\s*[=:]\s*)[^;\s\"']+"
                    r"|://[^/\s:@]+:[^@\s/]+@|\b(sk|ghp|xox[abprs])[-_][A-Za-z0-9_-]{10,}|-----BEGIN [A-Z ]*PRIVATE KEY", re.I)
FIELDS = [("run", "Run"), ("environment", "Environment detected"), ("data", "Test data used"),
          ("results", "Results"), ("coverage", "Coverage"), ("flaky", "Flaky tests"),
          ("gaps", "Known implementation gaps"), ("untested", "Untested neighbours")]
SKIP_DIRS = {".git", "bin", "obj", "node_modules", ".venv", "venv", "__pycache__", "dev-plans", ".howtoai"}


class Fail(Exception):
    pass


def out(obj, code=0):
    print(json.dumps(obj, ensure_ascii=False, indent=1))
    sys.exit(code)


def redact(text):
    def sub(m):
        if m.group(1):
            return m.group(1) + "[redacted]"
        if m.group(0).startswith("://"):
            return "://[redacted]@"
        return "[redacted]"
    return SECRET.sub(sub, text)


def as_text(v):
    if v is None or v == "" or v == []:
        return "none"
    if isinstance(v, list):
        return "; ".join(str(x) for x in v)
    return str(v)


def render_block(data):
    run = as_text(data.get("run"))
    commit = as_text(data.get("commit"))
    lines = [START,
             "Generated by `dev-test` on every run; rewritten in full and never edited by hand. Secrets are redacted.",
             "",
             f"- **Run:** {run} on commit `{commit}`"]
    for key, label in FIELDS[1:]:
        lines.append(f"- **{label}:** {as_text(data.get(key))}")
    lines.append(END)
    return redact("\n".join(lines))


def update(test_dir, data_file, create):
    path = os.path.join(test_dir, "TESTING.md")
    with open(data_file, encoding="utf-8") as f:
        data = json.load(f)
    if not isinstance(data, dict):
        raise Fail("--data must hold a JSON object")
    unknown = set(data) - {k for k, _ in FIELDS} - {"commit"}
    if unknown:
        raise Fail(f"unknown data keys: {sorted(unknown)}")
    if run_time(f"**Run:** {data.get('run', '')}") is None or "T" not in str(data.get("run", "")):
        raise Fail("run must be the run's ISO date and time, for example 2026-11-19T16:12:00+01:00")
    created = False
    if not os.path.isfile(path):
        if not create:
            raise Fail(f"{path} is missing; ask the user, then rerun with --create")
        with open(TEMPLATE, encoding="utf-8") as f:
            text = f.read().replace("{directory}", os.path.basename(os.path.abspath(test_dir)) or test_dir)
        created = True
    else:
        with open(path, encoding="utf-8") as f:
            text = f.read()
    if text.count(START) != 1 or text.count(END) != 1 or text.index(START) > text.index(END):
        raise Fail(f"{path} needs exactly one {START} ... {END} block")
    new = text[:text.index(START)] + render_block(data) + text[text.index(END) + len(END):]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)
    placeholders = sorted(set(re.findall(r"\{[^{}\n]{3,}\}", new[:new.index(START)])))
    return {"ok": True, "file": path.replace("\\", "/"), "created": created, "base_placeholders": placeholders}


def load_globs(ws, user_file):
    sys.dont_write_bytecode = True  # no __pycache__ in the plugin's dev-core folder, even without -B
    spec = importlib.util.spec_from_file_location("devcore", os.path.abspath(os.path.join(CORE, "scripts", "devcore.py")))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    try:
        settings, _ = mod.load_settings(ws, user_file)
    except mod.Fail as e:
        raise Fail(str(e))
    return [g for g in settings.get("testing", {}).get("test_globs", []) if not g.endswith("TESTING.md")]


def test_dirs(ws, globs):
    found = set()
    for root, dirs, files in os.walk(ws):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        rel = os.path.relpath(root, ws).replace("\\", "/")
        for f in files:
            if f == "TESTING.md":
                continue
            frel = f if rel == "." else f"{rel}/{f}"
            if any(fnmatch.fnmatch(frel, g) or fnmatch.fnmatch("/" + frel, g) for g in globs):
                top = top_test_dir(frel, globs)
                found.add(top)
                break
    return sorted(found)


TEST_DIR_NAME = re.compile(r"^(?:(?i:tests?|specs?|__tests__)|.+Tests?)$")


def top_test_dir(frel, globs):
    """The deepest folder on the path whose own name marks it as a test folder, else the file's folder."""
    parts = frel.split("/")[:-1]
    best = None
    for i, name in enumerate(parts):
        if TEST_DIR_NAME.match(name):
            best = "/".join(parts[:i + 1])
    return best or "/".join(parts) or "."


def git(ws, *args):
    try:
        p = subprocess.run(["git", "-C", ws, *args], capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return p.stdout.strip() if p.returncode == 0 else None


def run_time(text):
    m = re.search(r"\*\*Run:\*\*\s*(\S+)", text)
    if not m:
        return None
    try:
        t = datetime.datetime.fromisoformat(m.group(1).replace("Z", "+00:00"))
    except ValueError:
        return None
    return t if t.tzinfo else t.astimezone()


def last_change(ws, d):
    full = os.path.join(ws, d)
    in_git = git(ws, "rev-parse", "--is-inside-work-tree") == "true"
    if in_git:
        dirty = git(ws, "status", "--porcelain", "--", d)
        dirty = [l for l in (dirty or "").splitlines() if not l.rstrip().endswith("TESTING.md")]
        if dirty:
            return "uncommitted changes", None
        iso = git(ws, "log", "-1", "--format=%cI", "--", d)
        return "commit", datetime.datetime.fromisoformat(iso) if iso else None
    newest = 0.0
    for root, dirs, files in os.walk(full):
        dirs[:] = [x for x in dirs if x not in SKIP_DIRS]
        for f in files:
            if f != "TESTING.md":
                newest = max(newest, os.path.getmtime(os.path.join(root, f)))
    return "file time", datetime.datetime.fromtimestamp(newest).astimezone() if newest else None


def check(ws, user_file, dirs):
    globs = load_globs(ws, user_file)
    dirs = [d.replace("\\", "/").strip("/") or "." for d in dirs] if dirs else test_dirs(ws, globs)
    missing, stale, fresh = [], [], []
    for d in dirs:
        path = os.path.join(ws, d, "TESTING.md")
        if not os.path.isfile(path):
            missing.append(d)
            continue
        with open(path, encoding="utf-8") as f:
            text = f.read()
        ran = run_time(text)
        how, changed = last_change(ws, d)
        if how == "uncommitted changes":
            stale.append({"dir": d, "reason": "uncommitted changes after the last run"})
        elif ran is None:
            stale.append({"dir": d, "reason": "no readable Run time in the generated part"})
        elif changed and changed > ran:
            stale.append({"dir": d, "reason": f"last {how} {changed.isoformat()} is after the run {ran.isoformat()}"})
        else:
            fresh.append(d)
    return {"ok": True, "missing": missing, "stale": stale, "fresh": fresh, "passed": not missing and not stale}


def main(argv=None):
    ap = argparse.ArgumentParser(description="Write and check TESTING.md generated parts.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    u = sub.add_parser("update")
    u.add_argument("dir")
    u.add_argument("--data", required=True)
    u.add_argument("--create", action="store_true")
    c = sub.add_parser("check")
    c.add_argument("--workspace", required=True)
    c.add_argument("--user-file")
    c.add_argument("--dirs", nargs="*")
    a = ap.parse_args(argv)
    try:
        if a.cmd == "update":
            if not os.path.isdir(a.dir):
                raise Fail(f"not a folder: {a.dir}")
            out(update(a.dir, a.data, a.create))
        out(check(os.path.abspath(a.workspace), a.user_file, a.dirs))
    except (Fail, ValueError, OSError) as e:
        out({"ok": False, "error": str(e)}, 1)


if __name__ == "__main__":
    main()
